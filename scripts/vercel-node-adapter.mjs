/**
 * Nitro's Vercel preset emits a web-standard `{ fetch }` object as the default
 * export, but the emitted .vc-config.json declares `launcherType: "Nodejs"`,
 * whose launcher requires a `(req, res)` function. That mismatch makes every
 * request fail at runtime ("This page didn't load") even though the build is
 * green. This post-build step keeps Nitro's output untouched and wraps it in a
 * real Node handler.
 */
import { readFile, writeFile, rename, access } from 'node:fs/promises';
import path from 'node:path';

const funcDir = path.resolve('.vercel/output/functions/__server.func');
const entry = path.join(funcDir, 'index.mjs');
const nitroEntry = path.join(funcDir, 'nitro-entry.mjs');

try {
  await access(entry);
} catch {
  console.error('[vercel-adapter] no .vercel/output function found — skipping');
  process.exit(0);
}

const current = await readFile(entry, 'utf8');
if (current.includes('__vercel_node_adapter__')) {
  console.log('[vercel-adapter] already applied');
  process.exit(0);
}

await rename(entry, nitroEntry);

await writeFile(
  entry,
  `// __vercel_node_adapter__ — generated by scripts/vercel-node-adapter.mjs
import { Readable } from 'node:stream';
import nitro from './nitro-entry.mjs';

const fetchHandler = typeof nitro === 'function' ? nitro : nitro.fetch.bind(nitro);

export default async function handler(req, res) {
  const host = req.headers['x-forwarded-host'] || req.headers.host || 'localhost';
  const proto = req.headers['x-forwarded-proto'] || 'https';
  const url = new URL(req.url || '/', \`\${proto}://\${host}\`);

  const headers = new Headers();
  for (const [key, value] of Object.entries(req.headers)) {
    if (value === undefined) continue;
    if (Array.isArray(value)) for (const v of value) headers.append(key, v);
    else headers.set(key, value);
  }

  const method = req.method || 'GET';
  const hasBody = method !== 'GET' && method !== 'HEAD';

  const request = new Request(url, {
    method,
    headers,
    body: hasBody ? Readable.toWeb(req) : undefined,
    ...(hasBody ? { duplex: 'half' } : {}),
  });

  let response;
  try {
    response = await fetchHandler(request);
  } catch (error) {
    console.error('[vercel-adapter] handler error', error);
    res.statusCode = 500;
    res.end('Internal Server Error');
    return;
  }

  res.statusCode = response.status;
  response.headers.forEach((value, key) => {
    if (key.toLowerCase() === 'set-cookie') return;
    res.setHeader(key, value);
  });
  const setCookie = response.headers.getSetCookie?.();
  if (setCookie?.length) res.setHeader('set-cookie', setCookie);

  if (!response.body) {
    res.end();
    return;
  }
  Readable.fromWeb(response.body).pipe(res);
}
`,
  'utf8',
);

console.log('[vercel-adapter] wrapped Nitro output in a Node-compatible handler');
